  React.ElementRef<typeof TabsPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof TabsPrimitive.Trigger>
>(({ className, ...props }, ref) => (
  <TabsPrimitive.Trigger
    ref={ref}
    className={cn(
      "inline-flex items-center justify-center whitespace-nowrap rounded-md px-3 py-1 text-sm font-medium ring-offset-background cursor-pointer transition-all focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 disabled:cursor-not-allowed data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow fel:rounded-full fel:data-[state=active]:bg-card fel:data-[state=active]:font-semibold fel:data-[state=active]:text-foreground fel:data-[state=active]:shadow-none fel:dark:data-[state=active]:bg-foreground fel:dark:data-[state=active]:text-background zak:rounded-full zak:data-[state=active]:bg-card zak:data-[state=active]:shadow-sm",
      className,
    )}
    {...props}
  />
));
